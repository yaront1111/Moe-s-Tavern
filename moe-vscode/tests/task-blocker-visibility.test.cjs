function transpile(sourcePath) {
    return ts.transpileModule(fs.readFileSync(sourcePath, 'utf8'), {
        compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true }
    }).outputText;
}

const boardScript = fs.readFileSync(boardScriptPath, 'utf8');
const detailScript = fs.readFileSync(detailScriptPath, 'utf8');
const panelSource = transpile(panelPath);

// A stub that throws on any member it does not define, so a new IDE, DOM or
// transport dependency fails loudly instead of rendering against undefined.
function strict(name, members) {
    return new Proxy(members, {
        get(target, key) {
            if (typeof key === 'symbol' || key in target) { return Reflect.get(target, key); }
            throw new Error(`unexpected access to ${name}.${key}`);
        }
    });
}

const subscription = () => strict('Disposable', { dispose() {} });
const fakeUri = (base, ...segments) => ({ path: [base.path, ...segments].join('/') });
const fakeWebview = members => ({
    cspSource: 'vscode-webview://moe-test', asWebviewUri: uri => `vscode-webview://moe-test${uri.path}`, ...members
});

// Runs a transpiled extension module that may require only the given
// dependencies; any other require() throws.
function loadModule(source, filename, dependencies) {
    const module = { exports: {} };
    const context = vm.createContext({
        exports: module.exports, module, console,
        require: name => {
            if (Object.prototype.hasOwnProperty.call(dependencies, name)) { return dependencies[name]; }
            throw new Error(`unexpected require from ${path.basename(filename)}: ${name}`);
        }
    });
    vm.runInContext(source, context, { filename });
    return module.exports;
}

const fakeVscode = panel => ({
    ViewColumn: strict('vscode.ViewColumn', { One: 1 }), Uri: strict('vscode.Uri', { joinPath: fakeUri }),
    window: strict('vscode.window', { createWebviewPanel: () => panel })
});

// The panel module also exports the canonical TypeScript copy of the rule; the
// drift guard below asks it directly.
const panelModule = loadModule(panelSource, panelPath, { vscode: fakeVscode(null) });

// Renders one card with the real renderTaskCard of a freshly loaded board.js.
// The script's load-time retry timers are real and always cleared.
function renderCard(task, columnStatus) {
    const clears = [];
    const ignore = () => {};
    const byId = strict('document.getElementById', Object.fromEntries(['epicFilter', 'addEpicBtn', 'searchInput', 'searchClear']
        .map(id => [id, strict(`#${id}`, { addEventListener: ignore })])));
    const context = vm.createContext({
        acquireVsCodeApi: () => strict('vscodeApi', { getState: () => undefined, setState: ignore, postMessage: ignore }),
        document: strict('document', {
            addEventListener: ignore, body: strict('document.body', { addEventListener: ignore }), getElementById: id => byId[id]
        }),
        window: strict('window', { addEventListener: ignore }),
        setInterval: (fn, ms) => { const h = setInterval(fn, ms); clears.push(() => clearInterval(h)); return h; },
        setTimeout: (fn, ms) => { const h = setTimeout(fn, ms); clears.push(() => clearTimeout(h)); return h; },
        clearInterval, clearTimeout, console
    });
    try {
        vm.runInContext(boardScript, context, { filename: boardScriptPath });
        const column = columnStatus || (task.status === 'BLOCKED' ? 'WORKING' : task.status);
        return context.renderTaskCard(task, [], column);
    } finally {
        clears.forEach(clear => clear());
    }
}

// Opens the real TaskDetailPanel through createOrShow and returns the webview
// HTML it generated; the panel is disposed even when rendering throws.
function renderDetail(task) {
    const webview = fakeWebview({ html: '', onDidReceiveMessage: subscription });
    const panel = strict('WebviewPanel', { webview: strict('Webview', webview), onDidDispose: subscription, dispose() {} });
    const { TaskDetailPanel } = loadModule(panelSource, panelPath, { vscode: fakeVscode(panel) });
    const state = { tasks: [task], epics: [] };
    const client = strict('MoeDaemonClient', { currentState: state, onStateChanged: subscription });
    let opened;
    try {
        opened = TaskDetailPanel.createOrShow({ path: '/extension' }, client, task.id, state);
        return webview.html;
    } finally {
        if (opened) { opened.dispose(); }
    }
}

