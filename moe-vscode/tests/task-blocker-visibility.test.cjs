const CAUSE_OF_LABEL = {
    [RESOURCE_WAIT]: 'RESOURCE_WAIT', [DEPENDENCY_WAIT]: 'DEPENDENCY_WAIT', [EXTERNAL_BLOCK]: 'EXTERNAL_BLOCK'
};

test('the TypeScript rule and both webview copies agree on every fixture', () => {
    for (const [name, task, expectedLabel] of CAUSE_TABLE) {
        const expected = expectedLabel === null ? null : CAUSE_OF_LABEL[expectedLabel];

        assert.equal(panelModule.blockCause(task), expected, `TaskDetailPanel.blockCause disagrees on ${name}`);

        const cardLabels = blockerChips(renderCard(task)).filter(chip => chip.cls === 'chip-blocked').map(chip => chip.label);
        const cardCause = cardLabels.length === 0 ? null : CAUSE_OF_LABEL[cardLabels[0]];
        assert.equal(cardCause, expected, `media/board.js disagrees on ${name}`);

        const { element } = runLiveUpdate(makeTask({ status: 'WORKING' }), task);
        const liveCauses = textOf(liveLines(element), 'blocker-cause');
        const liveCause = liveCauses.length === 0 ? null : CAUSE_OF_LABEL[liveCauses[0]];
        assert.equal(liveCause, expected, `media/taskDetail.js disagrees on ${name}`);
    }
});

test('the TypeScript rule reads the attention flag verbatim and keeps recorded ids intact', () => {
    assert.equal(panelModule.needsHumanAttention(makeTask({ status: 'REVIEW', needsHumanReview: true })), true);
    assert.equal(panelModule.needsHumanAttention(makeTask({ status: 'BLOCKED', blockedReason: 'needs human review' })), false);
    assert.equal(panelModule.needsHumanAttention(makeTask({ status: 'REVIEW', needsHumanReview: 'true' })), false);
    assert.deepEqual(
        panelModule.blockedPrerequisiteIds(makeTask({ blockedOnTaskIds: ['task-zz', ' ', 'task-aa', 'task-zz'] })),
        ['task-zz', 'task-aa', 'task-zz']
    );
    // Array.from: an empty list built inside the vm realm is not reference-equal
    // to a host [], and deepStrictEqual compares prototypes.
    assert.deepEqual(Array.from(panelModule.blockedPrerequisiteIds(makeTask({ blockedOnTaskIds: 'task-a' }))), []);
    assert.deepEqual(Array.from(panelModule.blockedPrerequisiteIds(makeTask())), []);
    assert.deepEqual(Array.from(panelModule.blockedPrerequisiteIds(makeTask({ blockedOnTaskIds: ['', '  '] }))), []);
});
