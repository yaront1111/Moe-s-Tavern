// One element. `innerHTML` deliberately throws on both read and write: live
// updates must put daemon-supplied text in through a DOM text node, never by
// assembling markup, because a blockedReason is arbitrary agent output.
function makeNode(tagName, id, touched) {
    const node = {
        tagName, id, className: '', value: '', scrollTop: 0, scrollHeight: 0, dataset: {},
        children: [], text: '',
        appendChild(child) { if (id) { touched.add(id); } node.children.push(child); return child; },
        addEventListener() {}
    };
    Object.defineProperty(node, 'textContent', {
        get: () => (node.children.length > 0 ? node.children.map(child => child.textContent).join('') : node.text),
        set: value => { if (id) { touched.add(id); } node.children = []; node.text = String(value); }
    });
    const refuse = () => {
        throw new Error(`${tagName}#${id} innerHTML is not available: write daemon text with a DOM text node`);
    };
    Object.defineProperty(node, 'innerHTML', { get: refuse, set: refuse });
    return node;
}

// Loads the real media/taskDetail.js against that DOM, then delivers one
// updateTask message. Returns the nodes and the set of element ids the handler
// actually wrote to.
function runLiveUpdate(initialTask, updatedTask, editable = {}) {
    const touched = new Set();
    const nodes = {};
    const element = id => {
        if (!nodes[id]) { nodes[id] = makeNode('div', id, touched); }
        return nodes[id];
    };
    element('initial-data').dataset = { taskId: initialTask.id, taskStatus: initialTask.status };
    let onMessage;
    const context = vm.createContext({
        acquireVsCodeApi: () => strict('vscodeApi', { postMessage() {} }),
        document: strict('document', {
            getElementById: element,
            createElement: tag => makeNode(tag, null, touched),
            createTextNode: value => {
                const node = makeNode('#text', null, touched);
                node.textContent = value;
                return node;
            }
        }),
        window: strict('window', {
            addEventListener: (type, handler) => { if (type === 'message') { onMessage = handler; } }
        }),
        console
    });
    vm.runInContext(detailScript, context, { filename: detailScriptPath });
    if (typeof onMessage !== 'function') {
        throw new Error('taskDetail.js registered no message handler');
    }
    for (const [id, value] of Object.entries(editable)) { element(id).value = value; }
    touched.clear();
    onMessage({ data: { type: 'updateTask', task: updatedTask } });
    return { element, touched };
}

