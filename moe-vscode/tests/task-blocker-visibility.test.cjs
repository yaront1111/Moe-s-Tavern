const unescapeHtml = text => text
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#039;/g, "'")
    .replace(/&amp;/g, '&');

// The blocker section of the initial markup, as rendered lines.
function detailLines(html) {
    const open = '<div id="blockerSection">';
    const start = html.indexOf(open);
    assert.notEqual(start, -1, 'the detail markup has no #blockerSection wrapper');
    const inner = html.slice(start + open.length, html.indexOf('</div>\n', start));
    const lines = [];
    const pattern = /<div class="([^"]*)">([\s\S]*?)<\/div>/g;
    let match;
    while ((match = pattern.exec(inner)) !== null) {
        lines.push({ cls: match[1], text: unescapeHtml(match[2]) });
    }
    return lines;
}

// The same section after a live update, read off the DOM nodes.
const liveLines = element => element('blockerSection').children.map(child => ({ cls: child.className, text: child.textContent }));

const textOf = (lines, cls) => lines.filter(line => line.cls === cls).map(line => line.text);

// Every chip the card rendered, as { cls, title, label }.
function chipsOf(card) {
    const chips = [];
    const pattern = /<span class="chip ([^"]*)"(?: title="([^"]*)")?>([\s\S]*?)<\/span>/g;
    let match;
    while ((match = pattern.exec(card)) !== null) {
        chips.push({ cls: match[1], title: match[2] === undefined ? null : unescapeHtml(match[2]), label: match[3] });
    }
    return chips;
}

const blockerChips = card => chipsOf(card).filter(chip => chip.cls === 'chip-blocked' || chip.cls === 'chip-question');
const chipLabels = card => blockerChips(card).map(chip => chip.label);

